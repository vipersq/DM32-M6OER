"""The boot screen's picture (ui_draw_splash): an image into core/ui/splash_logo.c, scaled to SIZE px, on black, in
COLORS colors (the 16-color display keeps a few for the text), 4 bits a pixel.

    tools/splash_logo.py IMAGE [SIZE] [--preview OUT.png]
"""
import sys
from PIL import Image, ImageEnhance

COLORS = 13

def build(path, size):
    im = Image.open(path).convert("RGBA")
    bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
    im = Image.alpha_composite(bg, im).convert("RGB")
    # near-white edges (an image without transparency) as black too
    px = im.load()
    w, h = im.size
    stack = [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]
    seen = set()
    while stack:
        x, y = stack.pop()
        if (x, y) in seen or not (0 <= x < w and 0 <= y < h):
            continue
        r, g, b = px[x, y]
        if min(r, g, b) < 225:
            continue
        seen.add((x, y))
        px[x, y] = (0, 0, 0)
        stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    im = im.resize((size, size), Image.LANCZOS)
    # A small LCD reads darker than a monitor: lift the picture a little
    im = ImageEnhance.Contrast(ImageEnhance.Brightness(im).enhance(1.3)).enhance(1.15)
    # The palette from the picture's lit pixels (black is a color of its own: medians over a mostly black image would
    # spend most of it on near-blacks), the red rings kept by weighting the saturated pixels
    lit = []
    for c in (im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata()):
        r, g, b = c
        if max(c) > 24:
            lit.append(c)
            if r > 90 and r > 2 * g:
                lit += [c] * 6
    strip = Image.new("RGB", (len(lit), 1))
    strip.putdata(lit)
    sp = strip.quantize(colors=COLORS - 1, method=Image.Quantize.MEDIANCUT).getpalette()[:3 * (COLORS - 1)]
    pal = [(0, 0, 0)] + [tuple(sp[3 * i:3 * i + 3]) for i in range(COLORS - 1)]
    pimg = Image.new("P", (1, 1))
    pimg.putpalette([v for c in pal for v in c] + [0] * (768 - 3 * COLORS))
    q = im.quantize(palette=pimg, dither=Image.Dither.FLOYDSTEINBERG)
    return q, pal

def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    size = int(args[1]) if len(args) > 1 else 216
    q, pal = build(args[0], size)
    if "--preview" in sys.argv:
        q.convert("RGB").save(sys.argv[sys.argv.index("--preview") + 1])
    data = list(q.get_flattened_data()) if hasattr(q, 'get_flattened_data') else list(q.getdata())
    out = ["// SPDX-License-Identifier: MIT",
           "// Generated by tools/splash_logo.py from tools/art/splash_logo.png: do not edit",
           '#include "splash_logo.h"', "",
           "const uint16_t splash_logo_palette[SPLASH_LOGO_COLORS] = {"]
    out.append("\t" + ", ".join("0x%04X" % (((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)) for r, g, b in pal) + ",")
    out.append("};")
    out.append("const uint8_t splash_logo_pixels[SPLASH_LOGO_SIZE * SPLASH_LOGO_SIZE / 2] = {")
    by = [(data[i] << 4) | data[i + 1] for i in range(0, len(data), 2)]
    for i in range(0, len(by), 24):
        out.append("\t" + ", ".join("0x%02X" % b for b in by[i:i + 24]) + ",")
    out.append("};")
    open("core/ui/splash_logo.c", "w").write("\n".join(out) + "\n")
    open("core/ui/splash_logo.h", "w").write(
        "// SPDX-License-Identifier: MIT\n// The boot screen's picture (tools/splash_logo.py): SIZE x SIZE, 4 bits a pixel"
        " (high nibble left), each an index into the palette (RGB565)\n#ifndef UI_SPLASH_LOGO_H\n#define UI_SPLASH_LOGO_H\n"
        "#include <stdint.h>\n#define SPLASH_LOGO_SIZE\t%d\n#define SPLASH_LOGO_COLORS\t%d\n"
        "extern const uint16_t splash_logo_palette[SPLASH_LOGO_COLORS];\n"
        "extern const uint8_t splash_logo_pixels[SPLASH_LOGO_SIZE * SPLASH_LOGO_SIZE / 2];\n#endif\n" % (size, COLORS))
    print("palette:", pal)

main()
